from typing import Any, Literal
from pydantic import BaseModel, Field, model_validator


# Defines the structure and expected data for an individual task.
class Task(BaseModel):
    task_id: int
    description: str
    completion_criteria: str

    # Stores the IDs of tasks that must be completed before this task can run.
    # default_factory creates a separate empty list for each Task instance.
    depends_on: list[int] = Field(default_factory=list)
    task_type: Literal[
    'retrieval',
    'analysis',
    'synthesis'
]
    status: Literal[
        'pending',
        'processing',
        'completed',
        'failed'
        'blocked'
    ] = 'pending'

    # Any allows different types of results, such as strings, lists or dictionaries.
    result: Any = None

    # None means no error has occurred.
    error: str | None = None

# Defines the structure of an individual task generated by the AI Planner.
class TaskDraft(BaseModel):
    task_id: int
    description: str
    completion_criteria: str
    depends_on: list[int] = Field(default_factory=list)
    task_type: Literal[
    'retrieval',
    'analysis',
    'synthesis'
]

# Defines the structure of a task generated by the AI Planner.
class PlanDraft(BaseModel):
    tasks: list[TaskDraft]

# Defines the structure of a complete execution plan.
class Plan(BaseModel):
    tasks: list[Task]

    # Runs after Pydantic has validated the Plan's fields.
    # Checks whether task IDs and dependencies are logically valid.
    @model_validator(mode='after')
    def validate_dependencies(self):

        # Extract all task IDs from the plan into a list.
        task_ids = [task.task_id for task in self.tasks]

        # Ensure that no two tasks have the same ID.
        # set() removes duplicates, so different lengths indicate duplicate IDs.
        if len(task_ids) != len(set(task_ids)):
            raise ValueError('Task IDs must be unique.')

        # Create a set of all existing task IDs.
        # This makes it possible to check whether a dependency exists.
        known_ids = set(task_ids)

        # Validate the dependencies of every task in the plan.
        for task in self.tasks:

            # A task cannot depend on itself.
            if task.task_id in task.depends_on:
                raise ValueError(
                    f'Task {task.task_id} cannot depend on itself.'
                )

            # Ensure every referenced dependency belongs to this plan.
            for dependency in task.depends_on:
                if dependency not in known_ids:
                    raise ValueError(
                        f'Task {task.task_id} depends on '
                        f'unknown task {dependency}.'
                    )

        # Build a dictionary mapping each task ID to its dependencies.
        # Example: {1: [], 2: [1], 3: [2]}
        dependencies = {
            task.task_id: task.depends_on
            for task in self.tasks
        }

        # Tracks tasks that have been completely checked.
        visited = set()

        # Tracks tasks currently being explored by the cycle detection algorithm.
        visiting = set()

        # Uses Depth-First Search (DFS) to detect circular dependencies.
        def check_cycle(task_id):

            # If a task is encountered again on the current exploration path,
            # a circular dependency exists.
            if task_id in visiting:
                raise ValueError('Circular task dependency detected.')

            # No need to check a task that has already been fully explored.
            if task_id in visited:
                return

            # Mark this task as currently being explored.
            visiting.add(task_id)

            # Follow each dependency and recursively check its dependencies.
            for dependency in dependencies[task_id]:
                check_cycle(dependency)

            # Exploration of this task is complete.
            visiting.remove(task_id)
            visited.add(task_id)

        # Check every task to ensure the plan contains no dependency cycles.
        for task_id in task_ids:
            check_cycle(task_id)

        # Return the validated Plan instance.
        return self


# Manages task execution state and progress for a Plan.

class TaskManager:

    def __init__(self, plan: Plan):
        self.plan = plan

    # Finds the next pending task whose dependencies are completed.
    def get_next_task(self):

        # First, identify tasks that can no longer execute.
        self.update_blocked_tasks()

        for task in self.plan.tasks:

            if task.status != 'pending':
                continue

            dependencies_completed = all(
                self.get_task(dependency_id).status == 'completed'
                for dependency_id in task.depends_on
            )

            if dependencies_completed:
                return task

        return None

    # Marks a task as processing.
    def mark_processing(self, task_id: int):
        task = self.get_task(task_id)

        if task.status != 'pending':
            raise ValueError(
                f'Task {task_id} cannot enter processing '
                f'from status {task.status}.'
            )

        task.status = 'processing'

    # Marks a task as completed and stores its result.
    def mark_completed(self, task_id: int, result: Any):
        task = self.get_task(task_id)

        if task.status != 'processing':
            raise ValueError(
                f'Task {task_id} cannot be completed '
                f'from status {task.status}.'
            )

        task.status = 'completed'
        task.result = result
        task.error = None

    # Marks a task as failed and stores its error.
    def mark_failed(self, task_id: int, error: str):
        task = self.get_task(task_id)

        if task.status != 'processing':
            raise ValueError(
                f'Task {task_id} cannot fail '
                f'from status {task.status}.'
            )

        task.status = 'failed'
        task.error = error

        # Update dependent tasks after a failure.
        self.update_blocked_tasks()

    # Marks a task as blocked.
    def mark_blocked(self, task_id: int, reason: str):
        task = self.get_task(task_id)

        if task.status != 'pending':
            return

        task.status = 'blocked'
        task.error = reason

    # Automatically blocks tasks whose dependencies failed or were blocked.
    def update_blocked_tasks(self):

        changed = True

        while changed:
            changed = False

            for task in self.plan.tasks:

                if task.status != 'pending':
                    continue

                for dependency_id in task.depends_on:
                    dependency_task = self.get_task(dependency_id)

                    if dependency_task.status in ('failed', 'blocked'):
                        self.mark_blocked(
                            task.task_id,
                            f'Dependency Task {dependency_id} '
                            f'{dependency_task.status}.'
                        )

                        changed = True
                        break

    # Finds a task by its ID.
    def get_task(self, task_id: int):
        for task in self.plan.tasks:
            if task.task_id == task_id:
                return task

        raise ValueError(f'Task {task_id} not found.')

    # Checks whether execution has finished.
    def is_complete(self):
        return all(
            task.status in ('completed', 'failed', 'blocked')
            for task in self.plan.tasks
        )

    # Checks whether every task completed successfully.
    def is_successful(self):
        return all(
            task.status == 'completed'
            for task in self.plan.tasks
        )

    # Returns execution progress.
    def get_progress(self):
        return {
            'total': len(self.plan.tasks),
            'pending': sum(
                task.status == 'pending'
                for task in self.plan.tasks
            ),
            'processing': sum(
                task.status == 'processing'
                for task in self.plan.tasks
            ),
            'completed': sum(
                task.status == 'completed'
                for task in self.plan.tasks
            ),
            'failed': sum(
                task.status == 'failed'
                for task in self.plan.tasks
            ),
            'blocked': sum(
                task.status == 'blocked'
                for task in self.plan.tasks
            )
        }


